  get(weatherCode, coursesToday, temp) {
    const h = new Date().getHours();
    let category = 'day';
    if (h >= 6 && h < 9) category = 'morning';
    else if (h >= 17 && h < 21) category = 'evening';
    else if (h >= 21 || h < 6) category = 'night';

    if (weatherCode && weatherCode >= 300 && weatherCode < 500) {
      category = 'rain';
    } else if (temp !== undefined && temp !== null) {
      if (temp > 30) category = 'hot';
      else if (temp < 10) category = 'cold';
    }

    if (coursesToday !== undefined) {
      if (coursesToday >= 5) category = 'busy';
      else if (coursesToday <= 1) category = 'relax';
    }

    // 70% original messages, 30% book quotes
    if (Math.random() < 0.3 && this.book_quotes.length > 0) {
      return this.book_quotes[Math.floor(Math.random() * this.book_quotes.length)];
    }

    const msgs = this.pool[category] || this.pool.day;
    return msgs[Math.floor(Math.random() * msgs.length)];
  },

  update(el, weather, coursesCount) {
    const code = weather ? weather.icon : null;
    const temp = weather ? weather.temp : null;
    const msg = this.get(code, coursesCount, temp);
    el.textContent = msg;
  }
